#!/usr/bin/env bash
# Fetch the Ubuntu 24.04 build dependencies (Qt 6 + FFmpeg dev packages) into ./.deps
# WITHOUT root, for machines where `sudo apt install` is not possible.
#
# Preferred instead, when you have root:
#   sudo apt install build-essential cmake ninja-build pkg-config qt6-base-dev \
#        libavcodec-dev libavformat-dev libavutil-dev libswscale-dev
#
# Usage:
#   scripts/fetch-ubuntu-deps.sh          # creates .deps/{debs,root,ffmpeg,env.sh}
#   source .deps/env.sh                   # exports CMAKE_PREFIX_PATH, FFMPEG_ROOT, LD_LIBRARY_PATH, QT_PLUGIN_PATH
#   cmake --preset dev && cmake --build --preset dev
#
# Only packages that are not already installed system-wide are downloaded. The FFmpeg runtime
# libraries (libavcodec60, ...) must already be installed (they are on a stock desktop install).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEPS="${SCVP_DEPS_DIR:-$ROOT/.deps}"
ARCH="$(dpkg-architecture -qDEB_HOST_MULTIARCH 2>/dev/null || echo x86_64-linux-gnu)"

PKGS=(
  # Qt 6 runtime + development files
  libb2-1 libts0t64
  libqt6core6t64 libqt6gui6t64 libqt6widgets6t64 libqt6opengl6t64 libqt6openglwidgets6t64
  libqt6test6t64 libqt6dbus6t64 libqt6network6t64 libqt6concurrent6t64 libqt6printsupport6t64
  libqt6sql6t64 libqt6xml6t64
  qt6-base-dev qt6-base-dev-tools qmake6 qmake6-bin qt6-qpa-plugins
  # GL / X11 headers required by Qt6Gui's CMake package
  libgl-dev libglx-dev libopengl-dev libvulkan-dev libx11-dev libxau-dev libxcb1-dev libxdmcp-dev
  libpthread-stubs0-dev x11proto-core-dev x11proto-dev xtrans-dev
  # FFmpeg development files (headers + .so links; runtime libs come from the system)
  libavcodec-dev libavformat-dev libavutil-dev libswscale-dev libswresample-dev
  # Virtual X server for invisible GUI tests (scripts/xvfb-run.sh)
  xvfb
)

installed() { dpkg-query -W -f='${Status}' "$1" 2>/dev/null | grep -q "install ok installed"; }

mkdir -p "$DEPS/debs" "$DEPS/root"
cd "$DEPS/debs"
need=()
for p in "${PKGS[@]}"; do
  installed "$p" && continue
  compgen -G "${p}_*.deb" >/dev/null && continue
  need+=("$p")
done
if ((${#need[@]})); then
  echo "Downloading ${#need[@]} packages into $DEPS/debs"
  apt-get download "${need[@]}"
fi
for f in *.deb; do dpkg -x "$f" "$DEPS/root"; done

# Development symlinks (libfoo.so -> libfoo.so.N) of packages whose runtime part is installed
# system-wide point to files that are not in the extracted tree: repoint them to /usr/lib.
LIB="$DEPS/root/usr/lib/$ARCH"
for l in "$LIB"/*.so; do
  [ -L "$l" ] && [ ! -e "$l" ] || continue
  t="$(readlink "$l")"
  if [ -e "/usr/lib/$ARCH/$(basename "$t")" ]; then
    ln -sf "/usr/lib/$ARCH/$(basename "$t")" "$l"
  else
    echo "warning: $(basename "$l") -> $t has no runtime library installed" >&2
  fi
done

# FFMPEG_ROOT layout expected by cmake/ScvpFFmpeg.cmake
mkdir -p "$DEPS/ffmpeg"
ln -sfn "../root/usr/include/$ARCH" "$DEPS/ffmpeg/include"
ln -sfn "../root/usr/lib/$ARCH" "$DEPS/ffmpeg/lib"

cat > "$DEPS/env.sh" <<ENV
# Generated by scripts/fetch-ubuntu-deps.sh
export CMAKE_PREFIX_PATH="$DEPS/root/usr\${CMAKE_PREFIX_PATH:+:\$CMAKE_PREFIX_PATH}"
export FFMPEG_ROOT="$DEPS/ffmpeg"
export LD_LIBRARY_PATH="$LIB\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
export QT_PLUGIN_PATH="$LIB/qt6/plugins"
ENV
echo "Done. Run: source $DEPS/env.sh"
